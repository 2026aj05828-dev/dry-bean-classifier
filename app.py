from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt

from sklearn.metrics import (
    accuracy_score,
    roc_auc_score,
    precision_score,
    recall_score,
    f1_score,
    matthews_corrcoef,
    confusion_matrix,
    classification_report,
)
from sklearn.preprocessing import label_binarize

BASE_DIR = Path(__file__).resolve().parent
MODEL_DIR = BASE_DIR / "model"
TARGET = "Class"

MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "KNN": "knn.joblib",
    "Gaussian Naive Bayes": "naive_bayes.joblib",
    "Support Vector Machine": "svm.joblib",
}

st.set_page_config(
    page_title="Dry Bean Model Studio",
    page_icon="🌱",
    layout="wide",
)

st.title("🌱 Dry Bean Model Studio")
st.write(
    "Compare five trained classification models using "
    "labelled test data. Models are loaded from saved files; "
    "this application does not retrain them."
)

with st.sidebar:
    st.header("Model settings")
    selected_model = st.selectbox(
        "Choose a classifier",
        list(MODEL_FILES.keys()),
    )

uploaded_file = st.file_uploader(
    "Upload your test dataset (CSV)",
    type=["csv"],
)

if uploaded_file is None:
    st.info(
        "Upload test_data.csv generated by your training notebook. "
        "The file must contain all 16 input features and the "
        "actual Class column."
    )
    st.stop()

try:
    data = pd.read_csv(uploaded_file)
except Exception as exc:
    st.error(f"Could not read CSV: {exc}")
    st.stop()

if TARGET not in data.columns:
    st.error(
        "Your CSV must contain the target column named 'Class'."
    )
    st.stop()

y_true = data[TARGET].astype(str)
X_test = data.drop(columns=[TARGET]).copy()

model_path = MODEL_DIR / MODEL_FILES[selected_model]

if not model_path.exists():
    st.error(
        f"Model file not found: {model_path.name}. "
        "Check that all five trained models are in the model folder."
    )
    st.stop()

try:
    model = joblib.load(model_path)

    # Use the same feature names and order used during training.
    classifier = model.named_steps["classifier"]
    expected_features = list(classifier.feature_names_in_) if hasattr(
        classifier, "feature_names_in_"
    ) else None

    if expected_features:
        missing = [
            col for col in expected_features
            if col not in X_test.columns
        ]

        if missing:
            st.error(f"Missing input features: {missing}")
            st.stop()

        X_test = X_test[expected_features]

    y_pred = model.predict(X_test).astype(str)
    probabilities = model.predict_proba(X_test)

    classes = [str(c) for c in classifier.classes_]

    if len(classes) == 2:
        auc = roc_auc_score(
            y_true,
            probabilities[:, 1],
        )
    else:
        y_binary = label_binarize(
            y_true,
            classes=classes,
        )
        auc = roc_auc_score(
            y_binary,
            probabilities,
            average="macro",
        )

    metrics = {
        "Accuracy": accuracy_score(y_true, y_pred),
        "AUC (Macro OVR)": auc,
        "Precision (Macro)": precision_score(
            y_true, y_pred,
            average="macro",
            zero_division=0,
        ),
        "Recall (Macro)": recall_score(
            y_true, y_pred,
            average="macro",
            zero_division=0,
        ),
        "F1 (Macro)": f1_score(
            y_true, y_pred,
            average="macro",
            zero_division=0,
        ),
        "MCC": matthews_corrcoef(y_true, y_pred),
    }

except Exception as exc:
    st.error(f"Evaluation failed: {exc}")
    st.exception(exc)
    st.stop()

st.subheader(f"Results: {selected_model}")
st.caption(f"Test examples evaluated: {len(data)}")

columns = st.columns(3)

for i, (name, value) in enumerate(metrics.items()):
    columns[i % 3].metric(name, f"{value:.4f}")

st.subheader("Confusion Matrix")

labels = sorted(set(y_true) | set(y_pred))
cm = confusion_matrix(y_true, y_pred, labels=labels)

fig, ax = plt.subplots(figsize=(8, 6))
image = ax.imshow(cm, aspect="auto")
ax.set_xticks(range(len(labels)))
ax.set_yticks(range(len(labels)))
ax.set_xticklabels(labels, rotation=45, ha="right")
ax.set_yticklabels(labels)
ax.set_xlabel("Predicted class")
ax.set_ylabel("Actual class")
fig.colorbar(image, ax=ax)
fig.tight_layout()

st.pyplot(fig)
plt.close(fig)

st.subheader("Classification Report")

report = classification_report(
    y_true,
    y_pred,
    labels=labels,
    output_dict=True,
    zero_division=0,
)

st.dataframe(
    pd.DataFrame(report).transpose().round(3),
    use_container_width=True,
)

with st.expander("Preview uploaded test data"):
    st.dataframe(data.head(20), use_container_width=True)

st.download_button(
    "Download metrics as CSV",
    data=pd.DataFrame(
        [{"Model": selected_model, **metrics}]
    ).to_csv(index=False).encode("utf-8"),
    file_name="evaluation_metrics.csv",
    mime="text/csv",
)